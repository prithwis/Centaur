import random

def Shakuni(candidates, weights):

    selected_index = random.choices(
        range(len(candidates)),
        weights=weights,
        k=1
    )[0]

    reaction = candidates[selected_index]
    reaction.selection_weight = weights[selected_index]

    return reaction